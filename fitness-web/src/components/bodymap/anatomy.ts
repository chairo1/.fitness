// ---------------------------------------------------------------------------
// Muscles. `fiber` = fibre direction in degrees for the right-side shape (mirrored automatically).
// ---------------------------------------------------------------------------

export interface MuscleShape {
  part: string;
  d: string;
  fiber: number;
}

// The left copy is a mirror image, so its fibres run at the mirrored angle.
const mus = (part: string, fiber: number, ...shapes: Pt[][]): MuscleShape[] =>
  shapes.flatMap((pts) => pair(pts).map((d, i) => ({ part, d, fiber: i ? 180 - fiber : fiber })));

