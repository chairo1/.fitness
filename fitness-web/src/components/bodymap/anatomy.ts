// Vector anatomy chart (front + back). Each figure lives in a 400 × 900 box centred on x = 200.
// Shapes are authored for the right half of the image (x ≥ 200) as point lists and mirrored to the
// left; `smoothPath` turns them into closed Catmull-Rom curves.

export type Pt = [number, number] | [number, number, 1]; // third value 1 = sharp corner

export const FIGURE_W = 400;
export const FIGURE_H = 900;

/** Closed smooth path through the points (Catmull-Rom → cubic Bézier). */
export function smoothPath(points: Pt[]): string {
  const n = points.length;
  const p = (i: number) => points[(i + n) % n];
  let d = `M${p(0)[0]},${p(0)[1]}`;
  for (let i = 0; i < n; i++) {
    const p0 = p(i - 1), p1 = p(i), p2 = p(i + 1), p3 = p(i + 2);
    const t1 = p1[2] ? 0 : 1 / 6;
    const t2 = p2[2] ? 0 : 1 / 6;
    const c1x = p1[0] + (p2[0] - p0[0]) * t1;
    const c1y = p1[1] + (p2[1] - p0[1]) * t1;
    const c2x = p2[0] - (p3[0] - p1[0]) * t2;
    const c2y = p2[1] - (p3[1] - p1[1]) * t2;
    d += `C${c1x.toFixed(1)},${c1y.toFixed(1)} ${c2x.toFixed(1)},${c2y.toFixed(1)} ${p2[0]},${p2[1]}`;
  }
  return `${d}Z`;
}

const flip = (pts: Pt[]): Pt[] => pts.map(([x, y, c]) => (c ? [400 - x, y, 1] : [400 - x, y])).reverse() as Pt[];

/** A shape symmetric about x = 200: right-half outline from the top centre down to the bottom centre. */
export const symmetric = (half: Pt[]): string => smoothPath([...half, ...flip(half).slice(1, -1)]);

/** A shape on the right side plus its mirror image on the left. */
export const pair = (pts: Pt[]): string[] => [smoothPath(pts), smoothPath(flip(pts))];

